export function getToolAction(pluginId: string, actionName: string): ToolAction | undefined {
  return MOCK_TOOL_ACTIONS.find((a) => a.plugin_id === pluginId && a.name === actionName);
}

export function getToolPlugin(id: string): ToolPlugin | undefined {
  return MOCK_TOOL_PLUGINS.find((p) => p.id === id);
}

export function getActionsForPlugin(pluginId: string): ToolAction[] {
  return MOCK_TOOL_ACTIONS.filter((a) => a.plugin_id === pluginId);
}
