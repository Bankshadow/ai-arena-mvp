function plugin(
  partial: Omit<ToolPlugin, "available_actions" | "read_actions" | "write_actions">,
): ToolPlugin {
  const actions = MOCK_TOOL_ACTIONS.filter((a) => a.plugin_id === partial.id);
  return {
    ...partial,
    available_actions: actions.map((a) => a.name),
    read_actions: actions.filter((a) => a.kind === "read").map((a) => a.name),
    write_actions: actions.filter((a) => a.kind === "write").map((a) => a.name),
  };
}

