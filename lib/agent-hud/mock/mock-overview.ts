export function seedAgentHudStore(): AgentHudStoreData {
  const profiles = SEEDS.map(buildProfile);
  const healthSnapshots = SEEDS.map(buildHealthSnapshot);
  return {
    profiles,
    healthSnapshots,
    activity: buildActivity(),
    lastRefreshedAt: new Date().toISOString(),
  };
}

export function getSeedHealthInput(agentId: string) {
  return SEEDS.find((s) => s.id === agentId)?.healthInput;
}

