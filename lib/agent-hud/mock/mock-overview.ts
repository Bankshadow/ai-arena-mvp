function buildProfile(seed: SeedSpec): AgentHudProfile {
  const { score } = computeHealthScore(seed.healthInput);
  return {
    id: seed.id,
    name: seed.name,
    agentType: seed.agentType,
    status: seed.status,
    currentTask: seed.currentTask,
    constitutionVersion: seed.constitutionVersion,
    primaryProvider: seed.primaryProvider,
    primaryModel: seed.primaryModel,
    winRate: seed.winRate,
    averageScore: seed.averageScore,
    averageCostUsd: seed.averageCostUsd,
    totalTokens: seed.totalTokens,
    healthScore: score,
    memoryFreshness: seed.memoryFreshness,
    lastActiveAt: seed.lastActiveAt,
    riskLevel: seed.riskLevel,
    riskAlerts: seed.riskAlerts,
    accent: seed.accent,
  };
}

function buildHealthSnapshot(seed: SeedSpec): AgentHealthSnapshot {
  const { score, components } = computeHealthScore(seed.healthInput);
  return {
    agentId: seed.id,
    score,
    components,
    trend: score >= 80 ? "up" : score >= 60 ? "stable" : "down",
    updatedAt: new Date().toISOString(),
    summary:
      score >= 85
        ? "Operating within expected parameters."
        : score >= 70
          ? "Minor drift detected — monitor cost and errors."
          : "Elevated risk — review tool chain and constitution.",
  };
}

